import React, { useCallback, useState } from 'react';
import { View, Pressable, StyleSheet, TextInput, ScrollView } from 'react-native';
import { Text } from 'react-native-paper';
import { MaterialCommunityIcons as MCI } from '@expo/vector-icons';
import { useFocusEffect, useNavigation } from '@react-navigation/native';
import api, { errMsg } from '../../api';
import { useAuth } from '../../AuthContext';
import { useUi } from '../../ui';
import LoadingView from '../../components/LoadingView';
import EmptyView from '../../components/EmptyView';
import ConfirmDialog from '../../components/ConfirmDialog';
import SalesDetailModal from '../../components/SalesDetailModal';
import FgStockCardModal from '../../components/FgStockCardModal';
import { Panel } from '../../components/SalesBits';
import { MiniSelect, Box, DateBox, Field, Btn, Chip } from '../../components/SalesInputs';
import { ErrorBox, InfoBox, todayStr } from '../../components/FormBits';
import useLayout from '../../hooks/useLayout';
import { DATE_RE, nextKey, num } from '../../productionUtils';
import { CUSTOMER_TYPES, profitColor, r2, typeLabel } from './salesUtils';
import printInvoice from './printInvoice';
import { COLORS, SHADOW, fmt, money } from '../../theme';

// Invoice tab of New Sales Entry: one invoice, many products / SKUs.
//  - Invoice no is generated automatically (GET /sales/next-invoice-no previews it, the server assigns the real number on save).
//  - A new customer is added right here, inside the invoice.
//  - Every SKU shows the FINISHED GOODS stock (packs + kg); asking for more than is in stock shows how much is short.
//  - Payment is NOT taken here: cash / UPI / bank is recorded when the goods are delivered (Sales Delivery).
// GET /sales/lookups -> { customers, skus }   POST /sales/customers   POST /sales -> { id, invoice_no, total_amount }
const blankLine = () => ({ key: nextKey(), product_id: null, rate_id: null, qty: '', rate: '' });
const blankCust = () => ({ name: '', type: 'CUSTOMER', mobile: '', city: '', address: '', gst: '' });
const money2 = (v) => Number(v || 0).toLocaleString('en-IN', { minimumFractionDigits: 2, maximumFractionDigits: 2 });
const kgText = (v) => `${Number(v || 0).toLocaleString('en-IN', { maximumFractionDigits: 3 })} kg`;
const kgOf = (x, packs) => Math.round(Number(packs || 0) * Number(x?.weight_grams || 0)) / 1000;

function SumRow({ label, value, color, bold }) {
  return (
    <View style={s.sumRow}>
      <Text style={s.sumLabel}>{label}</Text>
      <Text style={[s.sumValue, bold && { fontWeight: '900' }, color && { color }]}>{value}</Text>
    </View>
  );
}

function Mini({ label, children, style }) {
  return (
    <View style={[s.mini, style]}>
      <Text style={s.miniLabel}>{label}</Text>
      {children}
    </View>
  );
}

export default function SalesInvoiceForm({ active = true, refreshKey = 0 }) {
  const { can } = useAuth();
  const { toast } = useUi();
  const nav = useNavigation();
  const { isWide, isPhone } = useLayout();
  const [lk, setLk] = useState(null);
  const [loadErr, setLoadErr] = useState('');
  const [autoNo, setAutoNo] = useState(true);       // invoice no generated by the server
  const [previewNo, setPreviewNo] = useState('');   // what the next auto number will be
  const [invoiceNo, setInvoiceNo] = useState('');   // only used when the user types their own
  const [date, setDate] = useState(todayStr());
  const [customerId, setCustomerId] = useState(null);
  const [notes, setNotes] = useState('');
  const [lines, setLines] = useState([blankLine()]);
  const [errors, setErrors] = useState({ lines: {} });
  const [confirm, setConfirm] = useState(false);
  const [printAfter, setPrintAfter] = useState(false);
  const [saving, setSaving] = useState(false);
  const [err, setErr] = useState('');
  const [done, setDone] = useState(null);          // saved invoice { id, invoice_no, total_amount }
  const [viewId, setViewId] = useState(null);
  const [stockSku, setStockSku] = useState(null);
  // inline "new customer" (inside the invoice itself)
  const [newCust, setNewCust] = useState(false);
  const [nc, setNc] = useState(blankCust());
  const [ncErr, setNcErr] = useState({});
  const [ncBusy, setNcBusy] = useState(false);
  const [ncMsg, setNcMsg] = useState('');

  // stock and customers change elsewhere, so lookups reload whenever this tab / page is shown (the form itself is kept)
  const loadLookups = useCallback(async () => {
    try { setLk((await api.get('/sales/lookups')).data.data); setLoadErr(''); } catch (e) { setLoadErr(errMsg(e)); }
  }, []);
  const loadNo = useCallback(async () => {
    try { setPreviewNo((await api.get('/sales/next-invoice-no')).data.data.invoice_no || ''); } catch (e) { setPreviewNo(''); }
  }, []);
  useFocusEffect(useCallback(() => { if (active) { loadLookups(); loadNo(); } }, [active, refreshKey, loadLookups, loadNo]));

  const skus = lk?.skus || [];
  const customers = lk?.customers || [];
  const customerOptions = customers.map((c) => ({
    value: c.id, short: c.name,
    label: `${c.name}${c.customer_type && c.customer_type !== 'CUSTOMER' ? ` · ${typeLabel(c.customer_type)}` : ''}${c.city ? ` · ${c.city}` : ''}`,
  }));
  const cust = customers.find((c) => c.id === customerId) || null;

  // finished goods stock per product (packs and kg)
  const stockOf = {};
  skus.forEach((x) => {
    const p = stockOf[x.product_id] || (stockOf[x.product_id] = { packs: 0, kg: 0 });
    p.packs += Number(x.stock_packs) || 0; p.kg += kgOf(x, x.stock_packs);
  });
  const productOptions = [];
  skus.forEach((x) => {
    if (productOptions.some((p) => p.value === x.product_id)) return;
    const st = stockOf[x.product_id];
    productOptions.push({ value: x.product_id, short: x.product_name, label: `${x.product_name} · ${st.packs > 0 ? `${kgText(st.kg)} in stock` : 'Out of stock'}` });
  });
  const skuOptions = (pid) => skus.filter((x) => x.product_id === pid)
    .map((x) => ({ value: x.packing_rate_id, short: x.packing_size_label, label: `${x.packing_size_label} · ${x.sku_code} · ${fmt(x.stock_packs)} packs (${kgText(kgOf(x, x.stock_packs))})` }));
  const stockRows = [];
  skus.filter((x) => Number(x.stock_packs) > 0).forEach((x) => {
    let g = stockRows.find((r) => r.product_id === x.product_id);
    if (!g) { g = { product_id: x.product_id, name: x.product_name, items: [] }; stockRows.push(g); }
    g.items.push(x);
  });

  const setLine = (key, patch) => setLines((p) => p.map((l) => (l.key === key ? { ...l, ...patch } : l)));
  const rateFor = (x) => (x ? String(x.selling_rate ?? x.mrp ?? '') : '');
  const pickProduct = (key, pid) => setLine(key, { product_id: pid, rate_id: null, rate: '' });
  const pickSku = (key, rid) => setLine(key, { rate_id: rid, rate: rateFor(skus.find((k) => k.packing_rate_id === rid)) });
  const removeLine = (key) => setLines((p) => (p.length > 1 ? p.filter((l) => l.key !== key) : p));
  // tapping a SKU in the stock panel puts it on the first empty line (or a new one)
  const addFromStock = (x) => {
    const patch = { product_id: x.product_id, rate_id: x.packing_rate_id, rate: rateFor(x) };
    setLines((p) => {
      const empty = p.find((l) => !l.rate_id);
      return empty ? p.map((l) => (l.key === empty.key ? { ...l, ...patch } : l)) : [...p, { ...blankLine(), ...patch }];
    });
  };

  // ---- inline new customer ----
  const setN = (k) => (v) => setNc((p) => ({ ...p, [k]: v }));
  const openNewCust = () => { setNc(blankCust()); setNcErr({}); setNcMsg(''); setNewCust(true); };
  const saveCust = async () => {
    const e = {};
    if (!nc.name.trim()) e.name = 'Enter the customer name';
    if (nc.mobile && !/^[0-9]{10}$/.test(nc.mobile.trim())) e.mobile = 'Mobile must be 10 digits';
    if (nc.gst && !/^[0-9]{2}[A-Z]{5}[0-9]{4}[A-Z][1-9A-Z]Z[0-9A-Z]$/.test(nc.gst.trim().toUpperCase())) e.gst = 'GST number is not valid';
    setNcErr(e);
    if (Object.keys(e).length) return;
    setNcBusy(true); setNcMsg('');
    try {
      const r = await api.post('/sales/customers', {
        customer_name: nc.name.trim(), customer_type: nc.type, mobile: nc.mobile.trim(), city: nc.city.trim(), address: nc.address.trim(), gst_number: nc.gst.trim(),
      });
      const c = r.data.data;
      await loadLookups();
      if (c?.id) { setCustomerId(c.id); setErrors((p) => ({ ...p, customer: undefined })); }
      setNewCust(false); toast('Customer added');
    } catch (x) { setNcMsg(errMsg(x)); }
    setNcBusy(false);
  };

  // ---- live figures ----
  const wanted = {};
  lines.forEach((l) => { if (l.rate_id) wanted[l.rate_id] = (wanted[l.rate_id] || 0) + Math.floor(num(l.qty)); });
  const calc = lines.map((l) => {
    const x = skus.find((k) => k.packing_rate_id === l.rate_id);
    const qty = Math.floor(num(l.qty));
    const rate = num(l.rate);
    const amount = r2(qty * rate);
    const cost = x && x.cost_per_pack !== null && x.cost_per_pack !== undefined ? Number(x.cost_per_pack) : null;
    return { x, qty, rate, amount, cost, profit: cost === null ? null : r2(amount - qty * cost) };
  });
  const totalPacks = calc.reduce((a, c) => a + c.qty, 0);
  const totalKg = calc.reduce((a, c) => a + kgOf(c.x, c.qty), 0);
  const gross = r2(calc.reduce((a, c) => a + c.amount, 0));
  const costed = calc.filter((c) => c.cost !== null && c.qty > 0);
  const estProfit = r2(costed.reduce((a, c) => a + (c.amount - c.qty * c.cost), 0));
  const missingCost = calc.some((c) => c.qty > 0 && c.x && c.cost === null);
  const filled = lines.filter((l) => l.rate_id && Math.floor(num(l.qty)) > 0).length;

  const validate = () => {
    const e = { lines: {} };
    if (!customerId) e.customer = newCust ? 'Save the new customer first' : 'Select or add the customer / agency';
    if (!autoNo) {
      if (!invoiceNo.trim()) e.invoiceNo = 'Enter the invoice no';
      else if (!/^[A-Za-z0-9][A-Za-z0-9/\-_.]*$/.test(invoiceNo.trim())) e.invoiceNo = 'Letters, numbers and - / _ . only';
    }
    if (!DATE_RE.test(date)) e.date = 'Use YYYY-MM-DD';
    else if (date > todayStr()) e.date = 'Date cannot be in the future';
    lines.forEach((l, i) => {
      const c = calc[i];
      const le = {};
      if (!l.product_id) le.product = 'Select the product';
      else if (!l.rate_id) le.sku = 'Select the pack size';
      if (l.rate_id && !(c.qty > 0)) le.qty = 'Enter the packs';
      else if (c.x && wanted[l.rate_id] > Number(c.x.stock_packs)) le.qty = `Only ${fmt(c.x.stock_packs)} packs in stock`;
      if (l.rate_id && !(c.rate > 0)) le.rate = 'Enter the rate';
      if (Object.keys(le).length) e.lines[i] = le;
    });
    setErrors(e);
    return !e.customer && !e.invoiceNo && !e.date && Object.keys(e.lines).length === 0;
  };
  const ask = (print) => { setErr(''); if (validate()) { setPrintAfter(!!print); setConfirm(true); } };

  const save = async () => {
    setConfirm(false); setSaving(true); setErr('');
    try {
      const r = await api.post('/sales', {
        invoice_no: autoNo ? undefined : invoiceNo.trim(), sale_date: date, customer_id: customerId, notes: notes.trim(),
        items: lines.map((l) => ({ packing_rate_id: l.rate_id, quantity: Math.floor(num(l.qty)), rate: num(l.rate) })),
      });
      const inv = r.data.data;
      setDone(inv); toast(`Invoice ${inv.invoice_no} saved`); loadLookups(); loadNo();
      if (printAfter) {
        try { if (!(await printInvoice(inv.id))) toast('Printing is available in the web app'); } catch (e) { toast(errMsg(e)); }
      }
    } catch (e) { setErr(errMsg(e)); }
    setSaving(false);
  };

  const reset = () => {
    setDone(null); setAutoNo(true); setInvoiceNo(''); setLines([blankLine()]); setNotes(''); setCustomerId(null); setDate(todayStr());
    setErrors({ lines: {} }); setErr(''); setNewCust(false); loadNo();
  };

  // ---- views ----
  const successView = done && (
    <View style={s.doneCard}>
      <View style={s.doneIcon}><MCI name="check-bold" size={34} color="#fff" /></View>
      <Text style={s.doneTitle}>Invoice {done.invoice_no} saved</Text>
      <Text style={s.doneSub}>{`${money(done.total_amount)} · finished goods stock updated`}</Text>
      <Text style={s.doneHint}>Payment will be recorded when the goods are delivered.</Text>
      <View style={s.doneBtns}>
        <Btn icon="receipt" label="View invoice" onPress={() => setViewId(done.id)} style={s.doneBtn} />
        <Btn icon="printer-outline" label="Print" onPress={async () => { try { if (!(await printInvoice(done.id))) toast('Printing is available in the web app'); } catch (e) { toast(errMsg(e)); } }} style={s.doneBtn} />
        {can('sales_delivery', 'view') && <Btn icon="truck-delivery-outline" label="Deliveries" onPress={() => nav.navigate('SalesDelivery')} style={s.doneBtn} />}
        <Btn icon="history" label="Sales history" onPress={() => nav.navigate('SalesHistory')} style={s.doneBtn} />
        <Btn icon="plus" label="New entry" filled onPress={reset} style={s.doneBtn} />
      </View>
    </View>
  );

  // one product card (called as a function, not a component, so typing never loses focus)
  const lineRow = (l, i) => {
    const c = calc[i];
    const le = errors.lines?.[i] || {};
    const avail = c.x ? Number(c.x.stock_packs) || 0 : 0;
    const need = c.x ? wanted[l.rate_id] || 0 : 0;
    const short = Math.max(need - avail, 0);
    const belowCost = c.cost !== null && c.rate > 0 && c.rate < c.cost;
    const aboveMrp = !!c.x && c.rate > Number(c.x.mrp) && Number(c.x.mrp) > 0;
    const msg = le.product || le.sku || le.qty || le.rate
      || (belowCost ? `Rate is below the actual cost of ${money(c.cost)} per pack: this line sells at a loss.` : aboveMrp ? `Rate is above the MRP of ${money(c.x.mrp)}.` : '');
    const msgErr = !!(le.product || le.sku || le.qty || le.rate);
    return (
      <View key={l.key} style={[s.card, (msgErr || short > 0) && { borderColor: COLORS.danger }]}>
        <View style={s.cardTop}>
          <View style={s.idx}><Text style={s.idxText}>{i + 1}</Text></View>
          <View style={{ flex: 1, flexDirection: isPhone ? 'column' : 'row', minWidth: 0 }}>
            <View style={[{ flex: 1.5 }, !isPhone && { marginRight: 10 }]}>
              <MiniSelect value={l.product_id} options={productOptions} onChange={(v) => pickProduct(l.key, v)} placeholder="Select product" title="product" error={le.product} searchable />
            </View>
            <View style={[{ flex: 1 }, isPhone && { marginTop: 8 }]}>
              <MiniSelect value={l.rate_id} options={skuOptions(l.product_id)} onChange={(v) => pickSku(l.key, v)} placeholder="Pack size" title="pack size" error={le.sku} disabled={!l.product_id} />
            </View>
          </View>
          <View style={s.cardActs}>
            {c.x && <Pressable onPress={() => setStockSku(c.x)} hitSlop={6} accessibilityLabel="Stock card" style={s.iconBtn}><MCI name="warehouse" size={19} color={COLORS.textSoft} /></Pressable>}
            <Pressable onPress={() => removeLine(l.key)} disabled={lines.length < 2} accessibilityLabel={`Remove item ${i + 1}`} hitSlop={6} style={[s.iconBtn, lines.length < 2 && { opacity: 0.35 }]}>
              <MCI name="trash-can-outline" size={20} color={COLORS.danger} />
            </Pressable>
          </View>
        </View>

        {/* finished goods stock of the chosen pack */}
        {!!c.x && (
          <View style={s.stockRow}>
            <View style={[s.stockChip, avail > 0 ? s.stockOk : s.stockBad]}>
              <MCI name="warehouse" size={15} color={avail > 0 ? COLORS.ok : COLORS.danger} />
              <Text style={[s.stockText, { color: avail > 0 ? COLORS.ok : COLORS.danger }]}>{avail > 0 ? `In stock: ${fmt(avail)} packs · ${kgText(kgOf(c.x, avail))}` : 'Out of stock'}</Text>
            </View>
            {need > 0 && (
              <View style={[s.stockChip, { backgroundColor: COLORS.greyBg }]}>
                <MCI name="cart-arrow-down" size={15} color={COLORS.textSoft} />
                <Text style={[s.stockText, { color: COLORS.textSoft }]}>{`Required: ${fmt(need)} packs · ${kgText(kgOf(c.x, need))}`}</Text>
              </View>
            )}
          </View>
        )}
        {short > 0 && (
          <View style={s.shortBox}>
            <MCI name="alert-circle-outline" size={18} color={COLORS.danger} />
            <Text style={s.shortText}>
              {`Only ${fmt(avail)} packs (${kgText(kgOf(c.x, avail))}) available. Short by ${fmt(short)} packs (${kgText(kgOf(c.x, short))}). Reduce the quantity or pack more stock first.`}
            </Text>
          </View>
        )}

        <View style={s.cardBottom}>
          <Mini label="Qty (packs)" style={{ flex: 1 }}><Box digits value={l.qty} onChange={(v) => setLine(l.key, { qty: v })} placeholder="0" error={le.qty} align="center" /></Mini>
          <Mini label="Rate (₹)" style={{ flex: 1 }}><Box numeric value={l.rate} onChange={(v) => setLine(l.key, { rate: v })} placeholder="0.00" error={le.rate} /></Mini>
          <Mini label="MRP (₹)" style={{ flex: 1 }}><Box editable={false} value={c.x && c.x.mrp !== null && c.x.mrp !== undefined ? money2(c.x.mrp) : ''} onChange={() => {}} placeholder="-" /></Mini>
          <Mini label="Amount (₹)" style={{ flex: 1.1 }}>
            <View style={s.amtBox}><Text style={s.amtText} numberOfLines={1}>{money2(c.amount)}</Text></View>
          </Mini>
        </View>
        {!!msg && <Text style={[s.rowNote, msgErr ? { color: COLORS.danger } : { color: COLORS.warn }]}>{msg}</Text>}
      </View>
    );
  };

  // right panel: details of the chosen customer, or the inline "new customer" form
  const customerPanel = (
    <Panel title={newCust ? 'New Customer' : 'Customer Details'} icon={newCust ? 'account-plus-outline' : 'account'}
      style={isWide ? { width: 360, marginLeft: 14, alignSelf: 'stretch' } : { marginTop: 12 }}
      right={newCust ? <Pressable onPress={() => setNewCust(false)} hitSlop={8}><Text style={s.link}>Cancel</Text></Pressable> : null}>
      {newCust ? (
        <View>
          <Field label="Name" req error={ncErr.name}><Box align="left" value={nc.name} onChange={setN('name')} placeholder="Customer / agency name" maxLength={150} error={ncErr.name} /></Field>
          <View style={s.chipRow}>
            {CUSTOMER_TYPES.map((t) => <Chip key={t.value} label={t.label} on={nc.type === t.value} onPress={() => setN('type')(t.value)} />)}
          </View>
          <Field label="Mobile" error={ncErr.mobile}><Box digits align="left" value={nc.mobile} onChange={setN('mobile')} placeholder="10 digit mobile" maxLength={10} error={ncErr.mobile} /></Field>
          <Field label="City"><Box align="left" value={nc.city} onChange={setN('city')} placeholder="City (optional)" maxLength={80} /></Field>
          <Field label="Address"><Box multiline align="left" value={nc.address} onChange={setN('address')} placeholder="Address (optional)" maxLength={500} /></Field>
          <Field label="GST No" error={ncErr.gst}><Box align="left" value={nc.gst} onChange={(t) => setN('gst')(t.toUpperCase())} placeholder="GST number (optional)" maxLength={15} error={ncErr.gst} /></Field>
          <ErrorBox text={ncMsg} />
          <Btn icon="check" label="Save & use this customer" filled onPress={saveCust} loading={ncBusy} disabled={!can('sales_entry', 'create')} style={{ marginLeft: 0, marginTop: 8 }} />
        </View>
      ) : !cust ? (
        <View style={s.custEmpty}>
          <MCI name="account-search-outline" size={34} color="#CDBFB5" />
          <Text style={s.custEmptyText}>Select a customer to see the details here</Text>
          <Pressable onPress={openNewCust} style={({ hovered }) => [s.linkBtn, hovered && { backgroundColor: COLORS.primarySoft }]}>
            <MCI name="plus" size={17} color={COLORS.primary} /><Text style={s.linkBtnText}>New customer</Text>
          </Pressable>
        </View>
      ) : (
        <View>
          <Text style={s.custName} numberOfLines={2}>{cust.name}</Text>
          <View style={s.custTags}>
            <View style={s.tag}><Text style={s.tagText}>{typeLabel(cust.customer_type)}</Text></View>
            {!!cust.customer_code && <Text style={s.custCode}>{cust.customer_code}</Text>}
          </View>
          {!!cust.contact_person && <View style={s.custRow}><MCI name="account-outline" size={19} color={COLORS.textSoft} /><Text style={s.custText}>{cust.contact_person}</Text></View>}
          {!!(cust.address || cust.city) && <View style={s.custRow}><MCI name="map-marker-outline" size={19} color={COLORS.textSoft} /><Text style={s.custText}>{[cust.address, cust.city].filter(Boolean).join(', ')}</Text></View>}
          {!!cust.mobile && <View style={s.custRow}><MCI name="phone-outline" size={19} color={COLORS.textSoft} /><Text style={s.custText}>{cust.mobile}</Text></View>}
          {!!cust.gst_number && <View style={s.custRow}><MCI name="card-account-details-outline" size={19} color={COLORS.textSoft} /><Text style={s.custText}>{`GST : ${cust.gst_number}`}</Text></View>}
          {!cust.contact_person && !cust.address && !cust.city && !cust.mobile && !cust.gst_number && <Text style={s.custNone}>No address, phone or GST saved for this customer.</Text>}
        </View>
      )}
    </Panel>
  );

  const summaryPanel = (
    <View style={isWide ? { width: 360, marginLeft: 14 } : { marginTop: 12 }}>
      <Panel title="Invoice Summary" icon="clipboard-text-outline">
        <SumRow label="Total Items" value={fmt(filled)} bold />
        <SumRow label="Total Qty" value={`${fmt(totalPacks)} packs`} bold />
        {totalKg > 0 && <SumRow label="Total Weight" value={kgText(totalKg)} bold />}
        <SumRow label="Subtotal" value={money(gross)} bold />
        {costed.length > 0 && <SumRow label="Estimated Profit" value={money(estProfit)} color={profitColor(estProfit)} bold />}
        <View style={s.grand}>
          <Text style={s.grandLabel}>Grand Total</Text>
          <Text style={s.grandValue} numberOfLines={1}>{money(gross)}</Text>
        </View>
        <View style={s.payNote}>
          <MCI name="truck-delivery-outline" size={18} color={COLORS.textSoft} />
          <Text style={s.payNoteText}>Payment (cash / UPI / bank) is recorded at delivery.</Text>
        </View>
        {missingCost && costed.length > 0 && <Text style={s.small}>Profit counts only the SKUs that have a cost recorded.</Text>}
        <ErrorBox text={err} />
      </Panel>

      <Panel title="Finished Goods Stock" icon="warehouse" style={{ marginTop: 12 }} right={<Text style={s.hint}>Tap to add</Text>}>
        {stockRows.length === 0 ? <Text style={s.custNone}>No finished goods in stock. Pack the products first.</Text> : (
          <ScrollView style={{ maxHeight: 280 }} nestedScrollEnabled showsVerticalScrollIndicator={false}>
            {stockRows.map((g) => (
              <View key={g.product_id} style={s.stGroup}>
                <View style={s.stHead}>
                  <Text style={s.stName} numberOfLines={1}>{g.name}</Text>
                  <Text style={s.stTotal}>{kgText(stockOf[g.product_id].kg)}</Text>
                </View>
                {g.items.map((x) => (
                  <Pressable key={x.packing_rate_id} onPress={() => addFromStock(x)} accessibilityRole="button"
                    style={({ hovered }) => [s.stRow, hovered && { backgroundColor: COLORS.primarySoft }]}>
                    <Text style={s.stPack} numberOfLines={1}>{x.packing_size_label}</Text>
                    <Text style={s.stQty}>{`${fmt(x.stock_packs)} packs · ${kgText(kgOf(x, x.stock_packs))}`}</Text>
                    <MCI name="plus-circle-outline" size={18} color={COLORS.primary} />
                  </Pressable>
                ))}
              </View>
            ))}
          </ScrollView>
        )}
      </Panel>
    </View>
  );

  const row = isWide ? { flexDirection: 'row', alignItems: 'flex-start' } : null;
  const three = { flexDirection: isPhone ? 'column' : 'row' };

  if (!lk && !loadErr) return <LoadingView rows={3} />;
  if (!lk) return <EmptyView error={loadErr} onRetry={loadLookups} />;
  if (done) return (
    <View>
      {successView}
      <SalesDetailModal visible={viewId !== null} id={viewId} onDismiss={() => setViewId(null)} />
    </View>
  );

  return (
    <View>
      {/* customer + customer details */}
      <View style={row}>
        <Panel title="Customer & Invoice Details" icon="storefront-outline" style={isWide ? { flex: 1, minWidth: 0 } : null}>
          <Field label="Customer / Agency" req error={errors.customer}>
            <MiniSelect value={customerId} options={customerOptions} onChange={(v) => { setCustomerId(v); setNewCust(false); setErrors((p) => ({ ...p, customer: undefined })); }}
              placeholder="Select customer / agency" title="customer / agency" error={errors.customer} searchable
              footer={{ label: 'Add new customer', onPress: openNewCust }} />
          </Field>
          <View style={[three, { marginTop: 8 }]}>
            <Field label="Invoice No" req={!autoNo} error={errors.invoiceNo} style={s.third}>
              {autoNo ? (
                <View style={[s.autoBox]}>
                  <Text style={s.autoNo} numberOfLines={1}>{previewNo || 'Auto'}</Text>
                  <View style={s.autoTag}><Text style={s.autoTagText}>AUTO</Text></View>
                  <Pressable onPress={() => { setAutoNo(false); setInvoiceNo(previewNo); }} hitSlop={8} accessibilityLabel="Type invoice no manually" style={{ marginLeft: 8 }}>
                    <MCI name="pencil-outline" size={18} color={COLORS.textSoft} />
                  </Pressable>
                </View>
              ) : (
                <View style={{ flexDirection: 'row', alignItems: 'center' }}>
                  <Box align="left" value={invoiceNo} onChange={(t) => { setInvoiceNo(t); setErrors((p) => ({ ...p, invoiceNo: undefined })); }} placeholder="Enter invoice no" maxLength={30} error={errors.invoiceNo} style={{ flex: 1 }} />
                  <Pressable onPress={() => { setAutoNo(true); setErrors((p) => ({ ...p, invoiceNo: undefined })); }} hitSlop={8} accessibilityLabel="Use automatic invoice no" style={{ marginLeft: 8 }}>
                    <MCI name="autorenew" size={22} color={COLORS.primary} />
                  </Pressable>
                </View>
              )}
            </Field>
            <Field label="Invoice Date" req error={errors.date} style={s.third}><DateBox value={date} onChange={setDate} error={errors.date} max={todayStr()} /></Field>
            <Field label="Payment" style={s.third}>
              <View style={s.autoBox}>
                <MCI name="truck-delivery-outline" size={18} color={COLORS.textSoft} />
                <Text style={[s.autoNo, { marginLeft: 8, fontWeight: '600', color: COLORS.textSoft }]} numberOfLines={1}>Collected at delivery</Text>
              </View>
            </Field>
          </View>
        </Panel>
        {customerPanel}
      </View>

      {/* products + summary / stock */}
      <View style={[row, { marginTop: 12 }]}>
        <Panel title="Add Products" icon="package-variant-closed" style={isWide ? { flex: 1, minWidth: 0 } : null}
          right={<Text style={s.hint}>{`${lines.length} item${lines.length === 1 ? '' : 's'}`}</Text>}>
          {!skus.length && <InfoBox text="No pack sizes found. Add the product pack sizes in Product & MRP first." />}
          {lines.map(lineRow)}
          <Pressable onPress={() => setLines((p) => [...p, blankLine()])} accessibilityRole="button"
            style={({ hovered }) => [s.addLine, hovered && { backgroundColor: COLORS.primarySoft }]}>
            <MCI name="plus-circle-outline" size={20} color={COLORS.primary} />
            <Text style={s.addLineText}>Add Another Product</Text>
          </Pressable>
        </Panel>
        {summaryPanel}
      </View>

      {/* notes + actions */}
      <View style={[s.bottom, SHADOW.sm, { flexDirection: isWide ? 'row' : 'column', alignItems: isWide ? 'flex-end' : 'stretch' }]}>
        <View style={{ flex: 1, minWidth: 0 }}>
          <View style={s.notesHead}><MCI name="note-text-outline" size={19} color={COLORS.textSoft} /><Text style={s.notesTitle}>Notes (Optional)</Text></View>
          <TextInput value={notes} onChangeText={setNotes} maxLength={255} multiline placeholder="Add notes, delivery instructions, etc..." placeholderTextColor="#B5ABA3" style={s.notes} />
        </View>
        <View style={[s.actions, isWide ? { marginLeft: 20 } : { marginTop: 14 }]}>
          <Btn label="Clear" onPress={reset} disabled={saving} />
          <Btn icon="content-save-outline" label="Save Invoice" onPress={() => ask(false)} loading={saving && !printAfter} disabled={saving || !can('sales_entry', 'create')} />
          <Btn icon="printer-outline" label="Save & Print" filled onPress={() => ask(true)} loading={saving && printAfter} disabled={saving || !can('sales_entry', 'create')} />
        </View>
      </View>

      <ConfirmDialog visible={confirm} busy={saving} title="Save this invoice?" confirmText={printAfter ? 'Save & Print' : 'Save Invoice'}
        message={`${cust ? cust.name : ''} · ${fmt(totalPacks)} packs (${kgText(totalKg)}) · ${money(gross)}. Finished goods stock will be reduced automatically.`}
        onConfirm={save} onCancel={() => setConfirm(false)} />
      <FgStockCardModal visible={!!stockSku} sku={stockSku} onDismiss={() => setStockSku(null)} />
    </View>
  );
}

